import fs from 'node:fs/promises';
import { FileBlob, SpreadsheetFile } from 'file:///C:/Users/ihao_ting.PMR.000/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs';

const [source, projectPreview, taskPreview] = process.argv.slice(2);
const workbook = await SpreadsheetFile.importXlsx(await FileBlob.load(source));
const tasks = workbook.worksheets.getItem('小工作總表');
const taskValues = tasks.getUsedRange(true).values;
const unfinished = taskValues.slice(1).filter(row => row[5] === '是');
const spcRelated = unfinished.filter(row => String(row[1] ?? '').includes('SPC'));
const taskRow = taskValues.findIndex(row => row[2] === 'SPC-CHEM-C1-EXCEL-ALIGN-1113-TASK-001') + 1;
if (!taskRow) throw new Error('Task row missing');
const project = workbook.worksheets.getItem('專案進度表');
const projectValues = project.getUsedRange(true).values;
const projectStart = projectValues.findIndex(row => row[0] === '2026-11-13：C1藥液計算與Excel三位精度對齊') + 1;
if (!projectStart) throw new Error('Project milestone missing');
const summary = (await workbook.inspect({kind:'table',range:'小工作總表!A1:K3',include:'values,formulas',tableMaxRows:3,tableMaxCols:11,maxChars:10000})).ndjson;
const task = (await workbook.inspect({kind:'table',range:`小工作總表!A${taskRow}:K${taskRow}`,include:'values,formulas',tableMaxRows:2,tableMaxCols:11,maxChars:9000})).ndjson;
const projectTable = (await workbook.inspect({kind:'table',range:`專案進度表!A${projectStart}:AK${projectStart + 3}`,include:'values,formulas',tableMaxRows:5,tableMaxCols:37,maxChars:12000})).ndjson;
const drawings = (await workbook.inspect({kind:'drawing',sheetId:'專案進度表',maxChars:200000})).ndjson;
const errors = (await workbook.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!|#SPILL!|#CALC!',options:{useRegex:true,maxResults:100},maxChars:3000})).ndjson;
if (unfinished.length !== 43 || spcRelated.length !== 19) throw new Error(`Unexpected counts ${unfinished.length}/${spcRelated.length}`);
if (!summary.includes('258') || !summary.includes('215') || !summary.includes('核心未完成43件')) throw new Error('Summary mismatch');
if (!task.includes('30.096') || !task.includes('SPC-CHEM-C1-EXCEL-ALIGN-1113-TASK-001')) throw new Error('Task row mismatch');
if (!projectTable.includes('六筆三位一致／Trace v2')) throw new Error('Project row mismatch');
if (!drawings.includes('SPC-CHEM-C1-EXCEL-ALIGN-1113-TASK-001 2026-11-13 測試資料完成')) throw new Error('Native milestone missing');
if (!errors.includes('matched 0')) throw new Error('Formula error scan failed');
workbook.recalculate();
const projectImage = await workbook.render({sheetName:'專案進度表',range:`A${projectStart}:AK${projectStart + 3}`,scale:1.2,format:'png'});
const taskImage = await workbook.render({sheetName:'小工作總表',range:`A${Math.max(1, taskRow - 2)}:K${taskRow}`,scale:1.2,format:'png'});
await fs.writeFile(projectPreview, new Uint8Array(await projectImage.arrayBuffer()));
await fs.writeFile(taskPreview, new Uint8Array(await taskImage.arrayBuffer()));
console.log(JSON.stringify({registered:258,completed:215,unfinished:unfinished.length,spcRelated:spcRelated.length,formulaErrors:0,taskRow,projectStart,task:'ok',milestone:'ok'}));
