export function createChartLabelTranslator(t, extra = {}) {
 return value => {
  if(typeof value !== 'string')return value;
  const key=Object.hasOwn(extra,value)?extra[value]:Object.hasOwn(chartLabelKeys,value)?'spc.chartLabels.'+chartLabelKeys[value]:null;
  if(key)return t(key);
  const type=/^(.*) 數值$/.exec(value);
  return type?t('spc.chartLabels.typeValue',{type:type[1]}):value;
 };
}
